"""Evaluate the number of tool calls made during each agent run.

The hook resets its counter when an agent run starts, records every
attempted tool invocation, warns on the final permitted call, and
returns a deny verdict for calls above the configured limit.

The middleware currently runs in evaluate-only mode, so verdicts are
audited without blocking tool execution.
"""

from agent_framework import create_agent_hooks_middleware

from agent_hooks import (
    ALLOW,
    AgentContext,
    Verdict,
)


# Maximum number of tool calls recommended for one agent execution.
MAX_TOOL_CALLS_PER_RUN = 4

# Stores the audit records generated by Agent Hooks.
tool_budget_records = []



class ToolCallBudgetGuard:
    """
    Count tool calls during each agent run.

    The fourth call generates a warning. Calls above the configured
    maximum return a deny verdict.
    """

    def __init__(
        self,
        maximum_tool_calls: int,
    ) -> None:
        self.maximum_tool_calls = maximum_tool_calls
        self.tool_calls_by_session: dict[str, int] = {}

    def intercept(
        self,
        context: AgentContext,
    ) -> Verdict:
        """Evaluate the number of tool calls in the current run."""

        interception_point = context["interception_point"]
        session_id = context["session"]["id"]

        # Start a new counter for every agent run.
        if interception_point == "agent_startup":
            self.tool_calls_by_session[session_id] = 0
            return ALLOW

        # Remove the counter when the run finishes.
        if interception_point == "agent_shutdown":
            self.tool_calls_by_session.pop(
                session_id,
                None,
            )
            return ALLOW

        if interception_point != "pre_tool_call":
            return ALLOW

        current_count = (
            self.tool_calls_by_session.get(session_id, 0)
            + 1
        )

        self.tool_calls_by_session[session_id] = current_count

        tool_name = context["tool_call"]["name"]

        print(
            f"[Agent Hook] Tool call {current_count}: "
            f"{tool_name}"
        )

        # The final permitted call produces a warning.
        if current_count == self.maximum_tool_calls:
            return Verdict.warn(
                reason="tool_budget_warning",
                message=(
                    "The agent has reached the recommended "
                    f"limit of {self.maximum_tool_calls} tool calls."
                ),
            )

        # Additional calls produce a deny verdict.
        if current_count > self.maximum_tool_calls:
            print(
                "[Agent Hook] This tool call would be blocked "
                "in enforce mode."
            )

            return Verdict.deny(
                reason="tool_budget_exceeded",
                message=(
                    "The maximum number of tool calls for this "
                    "request has been exceeded. Please make a "
                    "more specific request."
                ),
            )

        return ALLOW


tool_budget_guard = ToolCallBudgetGuard(
    maximum_tool_calls=MAX_TOOL_CALLS_PER_RUN
)


tool_budget_hooks = create_agent_hooks_middleware(
    {
        "tool-call-budget": tool_budget_guard,
    },
    mode="evaluate_only",
    record_sink=tool_budget_records.append,
)   